class PromoCodeCampaignLinkTests(TestCase):
    def test_valid_code_with_campaign(self) -> None:
        """A PromoCode can be linked to a Campaign."""
        campaign = Campaign.objects.create(name="Winter Launch 2025")
        promo = PromoCode.objects.create(
            code="WINTER10",
            campaign=campaign,
            discount_type=PromoCode.DiscountType.PERCENTAGE,
            value=Decimal("10"),
        )
        self.assertEqual(promo.campaign, campaign)
        self.assertIn(promo, campaign.promo_codes.all())

    def test_campaign_nullable(self) -> None:
        """PromoCode.campaign is nullable (standalone codes allowed)."""
        promo = PromoCode.objects.create(
            code="SOLO",
            discount_type=PromoCode.DiscountType.PERCENTAGE,
            value=Decimal("15"),
        )
        self.assertIsNone(promo.campaign)


class PromoCodeDefaultsTests(TestCase):
    def test_defaults(self) -> None:
        p = PromoCode.objects.create(
            code="DEF",
            discount_type=PromoCode.DiscountType.PERCENTAGE,
            value=Decimal("10"),
        )
        self.assertEqual(p.currency, "EGP")
        self.assertEqual(p.min_order_value, Decimal("0"))
        self.assertIsNone(p.usage_limit)
        self.assertIsNone(p.per_customer_limit)
        self.assertEqual(p.used_count, 0)
        self.assertTrue(p.is_active)

    def test_code_unique(self) -> None:
        PromoCode.objects.create(
            code="UNIQ",
            discount_type=PromoCode.DiscountType.PERCENTAGE,
            value=Decimal("10"),
        )
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                PromoCode.objects.create(
                    code="UNIQ",
                    discount_type=PromoCode.DiscountType.PERCENTAGE,
                    value=Decimal("20"),
                )


class PromoCodeValidityWindowTests(TestCase):
    def test_active_within_window(self) -> None:
        now = timezone.now()
        p = PromoCode.objects.create(
            code="NOW",
            discount_type=PromoCode.DiscountType.PERCENTAGE,
            value=Decimal("10"),
            starts_at=now - timedelta(days=1),
            ends_at=now + timedelta(days=1),
        )
        self.assertTrue(p.is_active)
        self.assertIsNotNone(p.starts_at)
        self.assertIsNotNone(p.ends_at)
