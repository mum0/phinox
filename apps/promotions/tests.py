"""
apps.promotions — tests for Campaign + PromoCode.

Covers:
  - PromoCode percentage bounds (0 <= value <= 100, reject 150)
  - PromoCode fixed discount must be > 0 (reject 0 or negative)
  - Valid code linked to a Campaign
  - min_order_value / usage_limit / per_customer_limit defaults
"""
from decimal import Decimal
from datetime import timedelta

from django.db import IntegrityError, transaction
from django.test import TestCase
from django.utils import timezone

from apps.promotions.models import Campaign, PromoCode


class CampaignTests(TestCase):
    def test_campaign_slug_autogenerated(self) -> None:
        c = Campaign.objects.create(name="Winter Launch 2025")
        self.assertEqual(c.slug, "winter-launch-2025")

    def test_campaign_defaults(self) -> None:
        c = Campaign.objects.create(name="Default Campaign")
        self.assertTrue(c.is_active)
        self.assertIsNone(c.starts_at)
        self.assertIsNone(c.ends_at)


class PromoCodePercentageBoundsTests(TestCase):
    def test_percentage_zero_allowed(self) -> None:
        """Percentage value=0 is valid (lower bound)."""
        p = PromoCode.objects.create(
            code="FREE",
            discount_type=PromoCode.DiscountType.PERCENTAGE,
            value=Decimal("0"),
        )
        self.assertEqual(p.value, Decimal("0"))

    def test_percentage_hundred_allowed(self) -> None:
        """Percentage value=100 is valid (upper bound)."""
        p = PromoCode.objects.create(
            code="ALLFREE",
            discount_type=PromoCode.DiscountType.PERCENTAGE,
            value=Decimal("100"),
        )
        self.assertEqual(p.value, Decimal("100"))

    def test_percentage_over_100_rejected(self) -> None:
        """CheckConstraint promo_percentage_bounds_0_100 rejects value=150."""
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                PromoCode.objects.create(
                    code="BAD150",
                    discount_type=PromoCode.DiscountType.PERCENTAGE,
                    value=Decimal("150"),
                )

    def test_percentage_negative_rejected(self) -> None:
        """CheckConstraint rejects negative percentage (also blocked by MinValueValidator)."""
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                PromoCode.objects.create(
                    code="NEG",
                    discount_type=PromoCode.DiscountType.PERCENTAGE,
                    value=Decimal("-5"),
                )


