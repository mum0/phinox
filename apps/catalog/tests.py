"""
apps.catalog — tests for Category, Product, ProductVariant.

Covers:
  - Product.business_id sequential generation (PHX-PROD-000001)
  - ProductVariant.sku per-family generation (PHX-WNT-001, PHX-WNT-002)
  - ProductVariant.unit_price computed property (base_price + price_extra)
  - CheckConstraints: base_price >= 0, price_extra >= 0
  - Category slug auto-generation
  - Simple product visibility on the public /products/ listing (Task PHINOX-FIX-VISIBILITY)
"""
from decimal import Decimal

from django.db import IntegrityError, transaction
from django.test import TestCase
from django.urls import reverse

from apps.catalog.models import Category, Collection, Product, ProductVariant


def make_category(name: str = "Winter", family_code: str = "WNT") -> Category:
    return Category.objects.create(name=name, family_code=family_code)


def make_product(category: Category, name: str = "Wool Coat", base_price: Decimal = Decimal("1000")) -> Product:
    return Product.objects.create(
        name=name,
        category=category,
        base_price=base_price,
        status=Product.Status.ACTIVE,
    )


def make_variant(product: Product, price_extra: Decimal = Decimal("0")) -> ProductVariant:
    return ProductVariant.objects.create(product=product, price_extra=price_extra)


class CategoryTests(TestCase):
    def test_category_slug_autogenerated(self) -> None:
        cat = Category.objects.create(name="Summer Collection", family_code="SUM")
        self.assertEqual(cat.slug, "summer-collection")

    def test_category_family_code_unique(self) -> None:
        Category.objects.create(name="Winter", family_code="WNT")
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                Category.objects.create(name="Winter 2", family_code="WNT")


class ProductBusinessIDTests(TestCase):
    def test_product_business_id_sequential(self) -> None:
        """Product business IDs are sequential: PHX-PROD-000001, PHX-PROD-000002."""
        cat = make_category()
        p1 = make_product(cat, name="Coat A")
        p2 = make_product(cat, name="Coat B")
        p3 = make_product(cat, name="Coat C")

        self.assertEqual(p1.business_id, "PHX-PROD-000001")
        self.assertEqual(p2.business_id, "PHX-PROD-000002")
        self.assertEqual(p3.business_id, "PHX-PROD-000003")

    def test_product_business_id_immutable(self) -> None:
        """business_id is editable=False and won't change on re-save."""
        cat = make_category()
        p = make_product(cat)
        original_bid = p.business_id
        p.name = "Renamed"
        p.save()
        p.refresh_from_db()
        self.assertEqual(p.business_id, original_bid)

    def test_product_business_id_unique(self) -> None:
        """business_id has a unique constraint."""
        cat = make_category()
        p = make_product(cat)
        # Forcing a duplicate via raw update — should be blocked
        p2 = make_product(cat, name="Second")
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                # Bypass the auto-gen by setting manually
                p2.business_id = p.business_id
                p2.save(update_fields=["business_id"])


