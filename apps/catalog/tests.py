# Task: PHINOX-FIX-VISIBILITY
# Simple smoke test that an active product actually renders on the public
# /products/ page (and the "No products found" empty state does NOT).
# Catches the view/template name mismatch class of bug — the view exposes
# the page under ``products`` (and an alias ``product_list``); the template
# iterates over ``products``. If they drift apart again, this test fires.
# ---------------------------------------------------------------------------
class ProductListViewVisibilityTest(TestCase):
    """Verify that active products appear in the rendered /products/ page."""

    @classmethod
    def setUpTestData(cls) -> None:
        cls.category = make_category(name="Jackets", family_code="JCK")
        cls.active_product = Product.objects.create(
            name="Phinox Signature Jacket",
            category=cls.category,
            base_price=Decimal("2500"),
            status=Product.Status.ACTIVE,
            is_active=True,
        )
        cls.draft_product = Product.objects.create(
            name="Draft Jacket (Hidden)",
            category=cls.category,
            base_price=Decimal("1000"),
            status=Product.Status.DRAFT,
            is_active=True,
        )

    def test_active_product_renders_on_listing(self) -> None:
        """The active product's name appears in the rendered HTML response.

        Asserts:
          - HTTP 200
          - Active product name "Phinox Signature Jacket" is present
          - Draft product name "Draft Jacket (Hidden)" is NOT present
          - The "No products found" empty state is NOT shown
        """
        url = reverse("catalog:product_list")
        response = self.client.get(url)

        self.assertEqual(response.status_code, 200)
        # Active product appears in context AND in rendered output.
        self.assertContains(response, "Phinox Signature Jacket")
        # Draft product must be hidden from shoppers.
        self.assertNotContains(response, "Draft Jacket (Hidden)")
        # Empty-state message must not fire when at least one active product exists.
        self.assertNotContains(response, "No products found")

    def test_context_exposes_products_and_alias(self) -> None:
        """Both ``products`` and ``product_list`` keys exist in context.

        The template iterates over ``products``; tests in tests_views.py
        fall back to ``product_list`` / ``object_list``. The view must
        surface both names so neither layer silently breaks.
        """
        url = reverse("catalog:product_list")
        response = self.client.get(url)

        self.assertEqual(response.status_code, 200)
        context = response.context
        self.assertIn("products", context, msg="template iterates over 'products'")
        self.assertIn("product_list", context, msg="legacy alias missing")
        self.assertIn("object_list", context, msg="ListView default alias missing")

        # All three keys must point at the same one active product.
        self.assertEqual(len(context["products"]), 1)
        self.assertEqual(len(context["product_list"]), 1)
        self.assertEqual(len(context["object_list"]), 1)
