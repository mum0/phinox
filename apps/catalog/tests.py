class ProductVariantSKUTests(TestCase):
    def test_variant_sku_sequential_per_family(self) -> None:
        """SKUs are sequential within a family: PHX-WNT-001, PHX-WNT-002."""
        cat = make_category(family_code="WNT")
        product = make_product(cat)
        v1 = make_variant(product)
        v2 = make_variant(product)
        v3 = make_variant(product)

        self.assertEqual(v1.sku, "PHX-WNT-001")
        self.assertEqual(v2.sku, "PHX-WNT-002")
        self.assertEqual(v3.sku, "PHX-WNT-003")

    def test_variant_sku_independent_families(self) -> None:
        """Different category families produce independent SKU sequences."""
        wnt = make_category(name="Winter", family_code="WNT")
        sumr = make_category(name="Summer", family_code="SUM")
        p_wnt = make_product(wnt, name="Wool Coat")
        p_sum = make_product(sumr, name="Linen Shirt")

        wnt_v1 = make_variant(p_wnt)
        sum_v1 = make_variant(p_sum)
        wnt_v2 = make_variant(p_wnt)
        sum_v2 = make_variant(p_sum)

        self.assertEqual(wnt_v1.sku, "PHX-WNT-001")
        self.assertEqual(wnt_v2.sku, "PHX-WNT-002")
        self.assertEqual(sum_v1.sku, "PHX-SUM-001")
        self.assertEqual(sum_v2.sku, "PHX-SUM-002")

    def test_variant_sku_immutable(self) -> None:
        """SKU is editable=False and won't regenerate on re-save."""
        cat = make_category()
        product = make_product(cat)
        v = make_variant(product)
        original_sku = v.sku
        v.name = "Large / Black"
        v.save()
        v.refresh_from_db()
        self.assertEqual(v.sku, original_sku)


