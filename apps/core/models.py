"""
apps.core — Shared abstract bases + Stable ID system.

The Stable ID system provides human-readable, sequential business IDs:
  - Order:    PHX-ORD-000001  (6-digit, zero-padded)
  - Customer: PHX-CUS-000001
  - Product:  PHX-PROD-000001
  - Payment:  PHX-PAY-000001
  - SKU:      PHX-WNT-001     (3-digit, per-family-code sequence)

IDs are generated atomically via IDSequence + select_for_update to prevent
race conditions under concurrent inserts. The internal PK remains
BigAutoField (Django default) — the business_id is a *separate* stable
identifier for external display / customer support / BOS reference.

Per دستور §6: NO BOS integration logic here — only the metadata fields
on Order (bos_sync_status, bos_reference_id, last_sync_at) which live in
apps.orders.models, not here.
"""
from django.db import models, transaction


# ---------------------------------------------------------------------------
# Abstract bases
# ---------------------------------------------------------------------------

class BaseModel(models.Model):
    """Abstract base: explicit BigAutoField PK + created_at / updated_at.

    Every concrete PHINOX model inherits from this (or from BusinessIDModel
    which extends it). BigAutoField is the internal PK — never exposed in
    URLs or APIs. The stable business_id (on BusinessIDModel subclasses)
    is the externally-visible identifier.
    """

    id = models.BigAutoField(primary_key=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        abstract = True


class BusinessIDModel(BaseModel):
    """Abstract base for models that carry a stable, human-readable business
    ID (e.g. PHX-ORD-000001, PHX-PROD-000001).

    Subclasses MUST set ``BUSINESS_ID_PREFIX`` (e.g. "ORD", "CUS", "PROD").
    The business_id is auto-generated on first save via next_business_id()
    and is immutable thereafter (editable=False).
    """

    business_id = models.CharField(
        max_length=30,
        unique=True,
        editable=False,
        blank=True,
        db_index=True,
    )

    BUSINESS_ID_PREFIX: str = ""

    class Meta:
        abstract = True

    def save(self, *args, **kwargs):
        if not self.business_id and self.BUSINESS_ID_PREFIX:
            self.business_id = next_business_id(self.BUSINESS_ID_PREFIX)
        super().save(*args, **kwargs)


# ---------------------------------------------------------------------------
# Stable ID system — atomic sequence generator
# ---------------------------------------------------------------------------

class IDSequence(models.Model):
    """Tracks the last-used sequential number for each ID prefix.

    Each row corresponds to one sequence (e.g. prefix="ORD" for orders,
    prefix="SKU_WNT" for Winter-family product SKUs). The next value is
    generated by atomically incrementing last_number inside a transaction
    with select_for_update, preventing duplicate IDs under concurrency.
    """

    prefix = models.CharField(max_length=30, unique=True)
    last_number = models.PositiveIntegerField(default=0)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "core_id_sequence"

    def __str__(self):
        return f"{self.prefix} → {self.last_number}"


def next_business_id(prefix: str) -> str:
    """Atomically generate the next business ID.

    Format: ``PHX-{PREFIX}-{6-digit zero-padded}``
    Example: prefix="ORD" → "PHX-ORD-000001", "PHX-ORD-000002", ...

    Uses select_for_update inside transaction.atomic to guarantee
    uniqueness under concurrent inserts. If the IDSequence row doesn't
    exist yet, it's created atomically via get_or_create.

    Args:
        prefix: The 3-letter prefix for this entity type (e.g. "ORD", "CUS").

    Returns:
        The formatted business ID string.
    """
    with transaction.atomic():
        seq, _created = IDSequence.objects.select_for_update().get_or_create(
            prefix=prefix,
            defaults={"last_number": 0},
        )
        seq.last_number += 1
        seq.save(update_fields=["last_number", "updated_at"])
        return f"PHX-{prefix}-{seq.last_number:06d}"


def next_sku(family_code: str) -> str:
    """Atomically generate the next SKU for a product family.

    Format: ``PHX-{FAMILY_CODE}-{3-digit zero-padded}``
    Example: family_code="WNT" → "PHX-WNT-001", "PHX-WNT-002", ...

    Each family_code gets its own independent sequence (tracked as
    prefix="SKU_{FAMILY_CODE}" in IDSequence), so SKUs are sequential
    within a category family.

    Args:
        family_code: The category's family_code (e.g. "WNT" for Winter).

    Returns:
        The formatted SKU string.
    """
    prefix = f"SKU_{family_code}"
    with transaction.atomic():
        seq, _created = IDSequence.objects.select_for_update().get_or_create(
            prefix=prefix,
            defaults={"last_number": 0},
        )
        seq.last_number += 1
        seq.save(update_fields=["last_number", "updated_at"])
        return f"PHX-{family_code}-{seq.last_number:03d}"
